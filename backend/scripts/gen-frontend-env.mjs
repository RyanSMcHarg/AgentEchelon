/**
 * Generate frontend/packages/chat/.env and frontend/packages/admin/.env from the
 * deployed CDK stack outputs, and frontend/packages/widget/.env when `widget` is a declared
 * capability. There is no root frontend/.env.
 *
 * The Vite build bakes these values in, and they only exist AFTER the backend
 * stacks deploy - so this reads them from the live CloudFormation outputs and
 * writes one .env per package, replacing the error-prone hand-copy step. The deployment
 * serves two HTTP APIs, so a package is handed two base URLs: `PersonApi` (both packages)
 * and `AdminApi` (the admin package only), with the capabilities each serves routes for.
 * Works the same in both analytics modes.
 *
 * Usage:
 *   node scripts/gen-frontend-env.mjs
 *   AE_INSTANCE_NAME=acme AWS_REGION=us-east-1 node scripts/gen-frontend-env.mjs
 *
 * Env:
 *   AE_INSTANCE_NAME / AE_STACK_PREFIX  the instance, as the CDK app reads it (default prefix
 *                                       "AgentEchelon"; scripts/lib/stack-lookup.cjs)
 *   STACK_PREFIX  script-only prefix override the CDK app does not read; deploy.mjs sets it
 *   AWS_REGION    region (default "us-east-1")
 */
import { writeFile } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { CloudFormationClient, DescribeStacksCommand } from '@aws-sdk/client-cloudformation';
import { SSMClient, GetParametersByPathCommand } from '@aws-sdk/client-ssm';

const require = createRequire(import.meta.url);
const { resolveStackPrefix, resolveInstanceName, isInstanceStack } = require('./lib/stack-lookup.cjs');
const { issuersFromConfig } = require('./lib/issuer-checks.cjs');
const { signInIssuers, viteIssuersLine } = require('./lib/sign-in-issuers.cjs');
const { missingOutputs } = require('./lib/frontend-env-requirements.cjs');
const { declaredCapabilities, contextFlagsFromConfig } = require('./lib/deploy-guards.cjs');
const { rowOf, clientClassificationsOfRows, readRowValues } = require('./lib/registry-client-classifications.cjs');

const REGION = process.env.AWS_REGION || 'us-east-1';
let PREFIX;
try {
  PREFIX = resolveStackPrefix(process.env);
} catch (err) {
  console.error(err.message);
  process.exit(1);
}
const __dirname = path.dirname(fileURLToPath(import.meta.url));
// Post workspace-split (DESIGN-SEPARATE-ADMIN-APP.md), the chat and admin apps are
// separate packages, each with its OWN .env that its own Vite build loads. The
// admin-only endpoint URLs go ONLY into the admin package's .env and never reach
// the public chat bundle.
const CHAT_ENV_PATH = path.resolve(__dirname, '../../frontend/packages/chat/.env');
const ADMIN_ENV_PATH = path.resolve(__dirname, '../../frontend/packages/admin/.env');
const WIDGET_ENV_PATH = path.resolve(__dirname, '../../frontend/packages/widget/.env');

/**
 * The widget's env: the person API and the app instance; the guest issuer's captcha site key, notice
 * version, the upgrade paths the visitor's conversation type declares and the chat app a visitor signs in
 * at, when the registry declares a guest issuer; and the origins a host assertion may be posted from
 * (every `allowedOrigins` of the registry's `host-assertion` entries). Nothing admin, no pool. Written when
 * `widget` is a declared capability.
 */
function widgetLines(outputs, registry) {
  const hosts = [...new Set((registry || []).filter((e) => e && e.kind === 'host-assertion').flatMap((e) => e.allowedOrigins || []))];
  const line = (name, value) => (value ? `${name}=${value}` : `# ${name} - not declared`);
  return [
    '# Generated by scripts/gen-frontend-env.mjs from deployed CDK outputs and the issuer registry.',
    '# Embeddable widget (@ae/widget) package env. No admin endpoint, no user pool.',
    `VITE_AWS_REGION=${REGION}`,
    line('VITE_APP_INSTANCE_ARN', outputs.AppInstanceArnOutput),
    line('VITE_PERSON_API_URL', outputs.PersonApiUrl),
    line('VITE_GUEST_CAPTCHA_SITE_KEY', outputs.GuestCaptchaSiteKey),
    line('VITE_GUEST_NOTICE_VERSION', outputs.GuestNoticeVersion),
    line('VITE_GUEST_UPGRADE_PATHS', outputs.GuestUpgradePaths === 'none' ? '' : outputs.GuestUpgradePaths),
    line('VITE_GUEST_SIGN_IN_URL', outputs.GuestSignInUrl),
    line('VITE_WIDGET_ASSERTION_HOSTS', hosts.join(',')),
  ];
}

// CloudFormation OutputKey -> frontend Vite variable. Keys are unique across the
// AgentEchelon stacks, so a single merged map is unambiguous.
const OUTPUT_TO_VITE = {
  // Analytics mode (athena|aurora). Checked FIRST by detectAnalyticsMode() so the app
  // uses the right endpoints without a probe (the probe can cache 'athena' if it runs
  // pre-login). Present as the AnalyticsMode output on the Archive stack, in both modes.
  AnalyticsMode: 'VITE_ANALYTICS_MODE',
  UserPoolId: 'VITE_USER_POOL_ID',
  UserPoolClientId: 'VITE_CLIENT_ID',
  // P3: dedicated admin app-client (present only when the admin app is deployed
  // without `-c adminAppClient=shared`). Admin package .env only; absent ⇒ reuse.
  AdminUserPoolClientId: 'VITE_ADMIN_CLIENT_ID',
  // The app client every provider federated into the pool signs in through (both apps), present only when
  // the registry federates one (`FederatedWebClient`, identity-stack.ts).
  UserPoolFederatedClientId: 'VITE_FEDERATED_CLIENT_ID',
  AppInstanceArnOutput: 'VITE_APP_INSTANCE_ARN',
  // THE DECLARED CLASSIFICATIONS ARE NOT HERE: the clients read them at load from `GET /classifications` on the
  // person API, which answers from the runtime registry, so a classification added later needs no frontend build.
  // EVERY ROUTE A PERSON CALLS, on one HTTP API behind the edge authorizer, and the capabilities whose
  // routes it serves (a feature is offered only where its route exists: battle, sharing).
  PersonApiUrl: 'VITE_PERSON_API_URL',
  PersonApiCapabilities: 'VITE_PERSON_API_CAPABILITIES',
  // EVERY ADMIN ROUTE, on one HTTP API behind IAM (the admin capability). Admin-only.
  AdminApiUrl: 'VITE_ADMIN_API_URL',
  AdminApiCapabilities: 'VITE_ADMIN_API_CAPABILITIES',
  // Told when a golden run, an upload or a generation ends (ADR-065). Absent, the console reads on Check again.
  ConsoleEventsHttpDns: 'VITE_CONSOLE_EVENTS_HTTP',
  ConsoleEventsRealtimeDns: 'VITE_CONSOLE_EVENTS_REALTIME',
  // Gates the DeploymentStatusBanner probe: only poll GET /deployment/state when sleep
  // mode is actually deployed. Absent (Athena mode) or 'false' ⇒ the banner never probes.
  SleepModeEnabled: 'VITE_SLEEP_MODE_ENABLED',
  // Drives whether the admin console shows the User Management tab or a pointer to the
  // configured IdP: `user-management.ts` drives Cognito User Pools directly, so it manages
  // nothing on a deployment that replaced them.
  IdentityProvider: 'VITE_IDENTITY_PROVIDER',
  // The separate admin console's URL (AgentEchelonAdminApp, prefix 'Admin').
  // The CHAT app reads it to show admins a link OUT to the console (a URL only, no
  // operator code). Absent until the admin frontend deploys (two-phase bootstrap);
  // a deployer can also override VITE_ADMIN_APP_URL to point at their own console.
  AdminDistributionUrl: 'VITE_ADMIN_APP_URL',
  // The widget's origin (the Widget stack, with the `widget` capability). The chat app takes a visitor's
  // sign-in hand-off (path A) only from a window on this origin (`requestPendingBindSecret`), so the value
  // is the deployment's own output and never a setting. Chat-only, and optional: without the widget there
  // is no hand-off to take.
  WidgetDistributionUrl: 'VITE_WIDGET_ORIGIN',
};

// Admin-ONLY Vite vars: the standalone admin console consumes these; the chat
// app does not (after the console split, DESIGN-SEPARATE-ADMIN-APP.md). They are
// written only to frontend/packages/admin/.env (loaded by the admin package's own
// `vite build`) and deliberately kept OUT of frontend/packages/chat/.env so the
// public chat bundle carries no admin endpoint URL. The person API is NOT here: the
// console resolves its person on it too, so it is shared and written to both.
const ADMIN_ONLY = new Set([
  'VITE_ADMIN_API_URL',
  'VITE_CONSOLE_EVENTS_HTTP',
  'VITE_CONSOLE_EVENTS_REALTIME',
  'VITE_ADMIN_API_CAPABILITIES',
  'VITE_ANALYTICS_MODE',
  // P3 (optional): a dedicated admin Cognito app-client. Absent ⇒ the admin app
  // falls back to VITE_CLIENT_ID (reuse of the shared client). Admin package only.
  'VITE_ADMIN_CLIENT_ID',
]);

// Chat-ONLY Vite vars: the chat SPA consumes these; the admin console does not.
// Everything that is neither ADMIN_ONLY nor CHAT_ONLY is SHARED and written to BOTH
// packages' .env (auth pool/client, the person API and its capabilities, the
// app-instance ARN used by admin's chime actions).
const CHAT_ONLY = new Set([
  // The admin-console LINK-OUT target: chat-only (the admin app does not link to
  // itself). A URL string, not an admin endpoint, so it is safe in the chat .env.
  'VITE_ADMIN_APP_URL',
  'VITE_SLEEP_MODE_ENABLED',
  'VITE_WIDGET_ORIGIN',
]);

// VITE vars that are optional: absent output ⇒ omit the line (the app degrades).
const OPTIONAL = new Set([
  'VITE_ANALYTICS_MODE',
  'VITE_SLEEP_MODE_ENABLED',
  // The admin API exists with the `admin` capability: without it there is no `<prefix>AdminApi`
  // stack, and the admin console has nothing to call.
  'VITE_ADMIN_API_URL',
  'VITE_ADMIN_API_CAPABILITIES',
  'VITE_ADMIN_CLIENT_ID',
  // This deployment's own pool exists only when the registry declares an issuer on it (L15).
  'VITE_USER_POOL_ID',
  'VITE_CLIENT_ID',
  // The standalone admin console exists with the `admin` capability: without it there is no
  // AgentEchelonAdminApp stack, so its `AdminDistributionUrl` output does not exist (see the
  // OUTPUT_TO_VITE comment). A default `cdk deploy --all` must NOT hard-fail env generation over a
  // console the deployer didn't ask for — omit the var (the chat app just hides the admin-console link).
  'VITE_ADMIN_APP_URL',
  // The widget exists with the `widget` capability; without it the chat app takes no hand-off.
  'VITE_WIDGET_ORIGIN',
  // The pool's federated app client exists only with a `cognito-federated` issuer on the pool, and is then
  // required by `missingOutputs` (scripts/lib/frontend-env-requirements.cjs).
  'VITE_FEDERATED_CLIENT_ID',
]);

async function collectOutputs() {
  const cfn = new CloudFormationClient({ region: REGION });
  const merged = {};
  let token;
  do {
    const resp = await cfn.send(new DescribeStacksCommand({ NextToken: token }));
    for (const stack of resp.Stacks || []) {
      // This instance's own stacks only: a bare prefix match also takes an instance whose name starts
      // with this one's (`Acme` and `AcmeTwo`) and merges its outputs into this env.
      if (!isInstanceStack(stack.StackName, PREFIX)) continue;
      for (const o of stack.Outputs || []) {
        if (o.OutputKey && o.OutputValue) merged[o.OutputKey] = o.OutputValue;
      }
    }
    token = resp.NextToken;
  } while (token);
  return merged;
}

/**
 * The redirect sign-in issuers, from the registry deploy.config.json declares (the same `issuers`
 * value deploy.mjs forwards to synth). Absent, the registry is the deployment's own pool alone, which signs in
 * with the password form, so there is nothing to list.
 */
/** backend/deploy.config.json, the declaration deploy.mjs forwards to synth, or {} when there is none. */
function deployConfig() {
  const configPath = path.resolve(__dirname, '../deploy.config.json');
  if (!existsSync(configPath)) {
    console.log('No backend/deploy.config.json: VITE_ISSUERS lists no redirect sign-in, and no capability is checked.');
    return {};
  }
  return JSON.parse(readFileSync(configPath, 'utf8'));
}

function issuersLine(outputs, config) {
  const { entries, skipped } = signInIssuers(issuersFromConfig(config), { selfPoolId: outputs.UserPoolId, region: REGION });
  for (const s of skipped) console.warn(`! issuer "${s.id}" is not offered at sign-in: ${s.reason}`);
  console.log(`Sign-in issuers: ${entries.length ? entries.map((e) => e.id).join(', ') : 'none (password sign-in only)'}`);
  return viteIssuersLine(entries);
}

/** `VITE_CLASSIFICATIONS` for the chat package, from this instance's registry rows (`<SSM root>/registry/classification`). */
async function chatFallbackClassificationsLine() {
  const instance = resolveInstanceName(process.env);
  const path = `/${instance}/registry/classification`;
  const values = await readRowValues(new SSMClient({ region: REGION }), GetParametersByPathCommand, path);
  if (!values.length) {
    console.warn(`! no registry rows under ${path}: the chat app's registration screen offers no classification until one is deployed`);
    return '# VITE_CLASSIFICATIONS: no registry rows found; the registration screen offers no classification';
  }
  const set = clientClassificationsOfRows(values.map(rowOf));
  console.log(`Classifications (chat fallback): ${set.map((c) => c.value).join(', ')}`);
  return `VITE_CLASSIFICATIONS=uri:${encodeURIComponent(JSON.stringify(set))}`;
}

async function main() {
  console.log(`Generating frontend/packages/{chat,admin}/.env from ${PREFIX}* stack outputs (${REGION})...`);
  const outputs = await collectOutputs();
  if (Object.keys(outputs).length === 0) {
    throw new Error(
      `No outputs found for stacks prefixed "${PREFIX}" in ${REGION}. ` +
        'Deploy the backend first (npm run deploy), or set AE_INSTANCE_NAME (or AE_STACK_PREFIX) and AWS_REGION.',
    );
  }

  // One .env per package. Each app's Vite loads only its own package's .env, so
  // the chat bundle can only carry vars written to the chat file. SHARED vars
  // (neither ADMIN_ONLY nor CHAT_ONLY) go to BOTH.
  const chatLines = [
    '# Generated by scripts/gen-frontend-env.mjs from deployed CDK outputs.',
    '# Do not edit by hand — re-run the script after a redeploy.',
    '# Chat SPA (@ae/chat) package env. No admin-only endpoint URLs.',
    `VITE_AWS_REGION=${REGION}`,
  ];
  const adminLines = [
    '# Generated by scripts/gen-frontend-env.mjs from deployed CDK outputs.',
    '# Admin console (@ae/admin) package env. Shared auth + admin-only endpoints.',
    `VITE_AWS_REGION=${REGION}`,
  ];
  const missingRequired = [];
  for (const [outputKey, viteVar] of Object.entries(OUTPUT_TO_VITE)) {
    // chat file gets everything except admin-only; admin file everything except chat-only.
    const targets = [];
    if (!ADMIN_ONLY.has(viteVar)) targets.push(chatLines);
    if (!CHAT_ONLY.has(viteVar)) targets.push(adminLines);
    const value = outputs[outputKey];
    for (const target of targets) {
      if (value) {
        target.push(`${viteVar}=${value}`);
      } else if (OPTIONAL.has(viteVar)) {
        target.push(`# ${viteVar} — not deployed (optional); feature degrades gracefully`);
      }
    }
    if (!value && !OPTIONAL.has(viteVar)) {
      missingRequired.push(`${viteVar} (output ${outputKey})`);
    }
  }

  // Shared: both apps render the sign-in screen. The admin console offers only the admin issuers.
  const config = deployConfig();
  const issuers = issuersLine(outputs, config);
  chatLines.push(issuers);
  adminLines.push(issuers);

  // THE CHAT APP'S FALLBACK SET, for what it renders before sign-in (the registration screen's classifications), from the
  // registry rows every handler reads. Signed in, both apps load the set from GET /classifications instead, so
  // the admin console carries none.
  chatLines.push(await chatFallbackClassificationsLine());

  // A DECLARED CAPABILITY, or a declared kind of sign-in, whose output is missing is refused: the bundle
  // would build and be unable to reach it (scripts/lib/frontend-env-requirements.cjs).
  const capabilities = declaredCapabilities(contextFlagsFromConfig({ capabilities: config.capabilities }));
  const registry = config.issuers === undefined || config.issuers === '' ? undefined : issuersFromConfig(config);
  for (const { key, why } of missingOutputs({ capabilities, issuers: registry, outputs })) {
    if (missingRequired.some((m) => m.includes(`(output ${key})`))) continue;
    missingRequired.push(`output ${key} (${why})`);
  }

  if (missingRequired.length) {
    throw new Error(
      `Missing required outputs — is the backend fully deployed?\n  - ${missingRequired.join('\n  - ')}`,
    );
  }

  await writeFile(CHAT_ENV_PATH, chatLines.join('\n') + '\n', 'utf8');
  console.log(`Wrote ${CHAT_ENV_PATH} (${chatLines.filter((l) => l.startsWith('VITE_')).length} vars).`);
  await writeFile(ADMIN_ENV_PATH, adminLines.join('\n') + '\n', 'utf8');
  console.log(`Wrote ${ADMIN_ENV_PATH} (${adminLines.filter((l) => l.startsWith('VITE_')).length} vars).`);
  if (capabilities.includes('widget')) {
    const lines = widgetLines(outputs, registry);
    await writeFile(WIDGET_ENV_PATH, lines.join('\n') + '\n', 'utf8');
    console.log(`Wrote ${WIDGET_ENV_PATH} (${lines.filter((l) => l.startsWith('VITE_')).length} vars).`);
  }

  const cf = outputs.DistributionUrl;
  if (cf) {
    console.log(`\nCloudFront: ${cf}`);
    console.log(
      `Reminder: for the app to call the API from CloudFront, the backend CORS must allow that origin —\n` +
        `deploy with --context appUrl=${cf} (see docs/guides/user/FRONTEND-DEPLOY.md).`,
    );
  }
}

main().catch((err) => {
  console.error('gen-frontend-env failed:', err.message || err);
  process.exit(1);
});
