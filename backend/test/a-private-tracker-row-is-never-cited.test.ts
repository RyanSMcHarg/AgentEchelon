/**
 * A PRIVATE TRACKER ROW IS NEVER CITED ON THE SHIPPED SURFACE.
 *
 * The open-work tracker lives in the gitignored `private/` directory. A reader of this repository
 * does not have it, so a comment, test title, SQL header or doc that points at one of its rows by
 * number points at nothing: the reference reads as authority and resolves to a dead end. Whatever the
 * row said belongs in the sentence that cites it, or in a public record (an ADR, a spec FR, a
 * LATENCY-TARGETS gap id), which a reader can open.
 *
 * The patterns are deliberately narrow, one per shape a citation has taken:
 *  - "tracker" followed by a number, with or without "row" or "rows" between them;
 *  - "row" or "rows" followed by a three-digit number, bare, hyphenated or parenthesized;
 *  - one of the tracker's working rules or review items by number ("tracker rule" plus a digit,
 *    "tracker C" plus a digit);
 *  - the tracker's fixes cited by item number ("tracker's ... (#" plus a digit);
 *  - a short row number named as an incident ("row-" plus a number, then "leak", "fix", "defect" or
 *    "incident").
 * A real data row ("row 1 of the table"), a SQL row count ("500 rows") and a numbered table row in a
 * public doc match none of them.
 *
 * Scope is every file git would ship: `git ls-files --cached --others --exclude-standard`, so a new
 * file is scanned before it is committed and a gitignored one never is, the same authority
 * `excludeIgnored` uses for the doc guards. A fixed list of roots and extensions missed whole kinds of
 * file (`.js`, `.json`, `.html`, `.css`, hooks, config), and a list drifts from the tree the moment a
 * directory is added. What is left out is listed below with its reason.
 */
import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

const REPO_ROOT = path.resolve(__dirname, '..', '..');

/** The private working directory: the tracker itself lives here and is never shipped. */
const PRIVATE_PREFIX = 'private/';

/** Lockfiles: generated by the package manager, and their integrity hashes are not prose. */
const LOCKFILES = new Set(['package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml']);

/** Binary files: nothing in them is read as a sentence. */
const BINARY_EXTENSIONS = new Set([
  '.png', '.jpg', '.jpeg', '.gif', '.ico', '.webp', '.bmp', '.pdf', '.zip', '.gz',
  '.woff', '.woff2', '.ttf', '.otf', '.eot', '.pem', '.mp3', '.mp4', '.wav',
]);

/**
 * Generated files, named so the exclusion is visible. Each is produced from a source this guard
 * already scans, so a citation is fixed at the source and the copy follows on regeneration.
 *  - `.d.ts`: compiler output beside the `.ts` it declares.
 *  - `docs/reference/e2e-coverage-matrix.md`: generated from the e2e test titles.
 */
const GENERATED_FILES = new Set(['docs/reference/e2e-coverage-matrix.md']);

const PATTERNS: RegExp[] = [
  /\btracker (rows? )?#?\d+/i,
  /\brows?[ -]#?\d{3}\b/i,
  /\btracker rule \d/i,
  /\btracker C\d+\b/i,
  /\btracker['’]s\b[^\n]{0,40}\(#\d+/i,
  /\brow-\d{1,3} (leak|fix|defect|incident)\b/i,
];

function shippedFiles(): string[] {
  // A guard that cannot enumerate the tree must fail rather than pass on an empty set; the corpus
  // assertion below is what turns a failed listing into a failure.
  const out = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return out
    .split('\0')
    .filter(Boolean)
    .map((rel) => rel.replace(/\\/g, '/'))
    .filter((rel) => !rel.startsWith(PRIVATE_PREFIX))
    .filter((rel) => !LOCKFILES.has(path.posix.basename(rel)))
    .filter((rel) => !BINARY_EXTENSIONS.has(path.posix.extname(rel).toLowerCase()))
    .filter((rel) => !rel.endsWith('.d.ts') && !GENERATED_FILES.has(rel))
    .map((rel) => path.join(REPO_ROOT, rel))
    // A file deleted in the working tree is still in the index until it is committed.
    .filter((abs) => fs.existsSync(abs) && fs.statSync(abs).isFile());
}

describe('a private tracker row is never cited', () => {
  const files = shippedFiles();

  it('scans a realistic corpus, so an empty walk cannot pass as compliance', () => {
    expect(files.length).toBeGreaterThan(500);
  });

  it('every pattern fires on the shape it exists for', () => {
    // Built from parts so this file does not itself carry the shape it bans.
    const shapes: Array<[number, string]> = [
      [0, ['(tracker', 'row', '381)'].join(' ')],
      [1, ['(row', '340)'].join(' ')],
      [1, ['the', 'row-' + '104', 'unit tests'].join(' ')],
      [1, ['rows', '#' + '210'].join(' ')],
      [2, ['tracker', 'rule', '2'].join(' ')],
      [3, ['(tracker', 'C' + '3)'].join(' ')],
      [4, ['the', "tracker's", 'nav fixes', '(#' + '4)'].join(' ')],
      [5, ['the', 'row-' + '82', 'leak'].join(' ')],
    ];
    for (const [i, shape] of shapes) expect([shape, PATTERNS[i].test(shape)]).toEqual([shape, true]);
    // The ordinary uses of the same words stay clear.
    for (const ok of ['row 1 of the table', 'inserted 500 rows', 'a row count of 42', 'the issue tracker']) {
      expect([ok, PATTERNS.some((p) => p.test(ok))]).toEqual([ok, false]);
    }
  });

  it('no shipped file cites a private tracker row by number', () => {
    const hits: string[] = [];
    for (const file of files) {
      const raw = fs.readFileSync(file);
      if (raw.subarray(0, 8000).includes(0)) continue; // an unlisted binary type: no sentences in it
      const lines = raw.toString('utf8').split(/\r?\n/);
      lines.forEach((line, i) => {
        if (PATTERNS.some((p) => p.test(line))) {
          hits.push(`${path.relative(REPO_ROOT, file).replace(/\\/g, '/')}:${i + 1}: ${line.trim().slice(0, 160)}`);
        }
      });
    }
    if (hits.length > 0) {
      throw new Error(
        'These lines cite a row of the private tracker, which a reader of this repository cannot open. '
        + 'State what the row said in the sentence itself, or cite a public record instead:\n'
        + hits.join('\n'),
      );
    }
  });
});
